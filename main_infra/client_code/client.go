// Create a global pool of byte slices to reuse memory across goroutines, in case the project goes to a 65k port option
var bufPool = sync.Pool{
	New: func() interface{} {
		return make([]byte, 1024)
	},
}

type dialResult struct {
	port   string
	status string
}

var c2_server_ip string
var c2_hostname ="c2.egress-whisperer.local"
var timeout time.Duration

var http_request_string = "GET /index.html HTTP/1.1\r\n" +
           "Host: " + c2_hostname + "\r\n" +
           "User-Agent: Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36\r\n" +
           "Accept: text/html,application/xhtml+xml,application/xml;q=0.9,image/avif,image/webp,*/*;q=0.8\r\n" +
           "Accept-Language: en-US,en;q=0.5\r\n" +
           "Connection: close\r\n" + 
           "\r\n"

func invokeParallelDialups(port string, wg *sync.WaitGroup, resultChan chan<- dialResult){
	
	defer wg.Done()

	var con_type string
	if port=="53"||port=="123"{ con_type="udp" } else {con_type ="tcp"}

	conn, err := net.DialTimeout(con_type, c2_server_ip+":"+port, timeout)
	if err!=nil{
		log.Println(err)
		//fmt.Println("port "+port+" coming mark 1")
		resultChan <- dialResult{port: port, status: err.Error()}
		return
	}
	defer conn.Close()

	conn.SetDeadline(time.Now().Add(timeout))

	switch port {
	case "443", "8443":
		config := &utls.Config{InsecureSkipVerify: true}
		uConn := utls.UClient(conn, config, utls.HelloChrome_Auto)
		uConn.SetDeadline(time.Now().Add(timeout))

		err = uConn.Handshake()
		if err != nil {
			log.Println("TLS Handshake Blocked or Failed:", err)
			resultChan <- dialResult{port: port, status: err.Error()}
			return
		}
		defer uConn.Close()

		fmt.Fprintf(uConn, http_request_string)
		
		// Borrow a buffer from the pool
		buf := bufPool.Get().([]byte)
		// Return to the pool when the function exits
		defer bufPool.Put(buf)

		n, err := uConn.Read(buf)
		if err!=nil{
			log.Println(err)
			//fmt.Println("port "+port+" coming mark 6")
			resultChan <- dialResult{port: port, status: err.Error()}
			return
		}
		
		if strings.Contains(string(buf[:n]), "200 OK"){
			resultChan <- dialResult{port: port, status: "success for "+port}
		}else{
			resultChan <- dialResult{port: port, status: "https did not return 200"}
		}

	case "80", "8080", "9001":
		fmt.Fprintf(conn, http_request_string)
		
		// Borrow a buffer from the pool
		buf := bufPool.Get().([]byte)
		// Return to the pool when the function exits
		defer bufPool.Put(buf)

		n, err := conn.Read(buf)
		if err!=nil{
			log.Println(err)
			//fmt.Println("port "+port+" coming mark 5")
			resultChan <- dialResult{port: port, status: err.Error()}
			return
		}
		
		if strings.Contains(string(buf[:n]), "200 OK"){
			resultChan <- dialResult{port: port, status: "success for "+port}
		}else{
			resultChan <- dialResult{port: port, status: "http did not return 200"}
		}

	case "53":
		payload:= []byte{
			byte(rand.Intn(256)), byte(rand.Intn(256)), //random transaction ID of 2 bytes
			0x01, 0x00, //00000001 00000000 = QR=0 (query), OPCODE = 0000 (standard query code)
							//AA=0not authoritative, TC=0 truncate, RD=1 recursion desired
							//RA, Z, Rcode = 0 i.e recursion not avalable, there was no error
			0x00, 0x01, //question count = 1
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, //anser, authoritaty, additional counts = 0 (2bytes each)

			// question section — querying "c2.egress-whisperer.local" --generated by AI
		    0x02, 'c', '2',
		    0x10, 'e', 'g', 'r', 'e', 's', 's', '-', 'w', 'h', 'i', 's', 'p', 'e', 'r', 'e', 'r',
		    0x05, 'l', 'o', 'c', 'a', 'l',
		    0x00,       // end of domain
		    0x00, 0x01, // QTYPE  = A
		    0x00, 0x01, // QCLASS = IN
		}
		//fmt.Println("DNS - ", payload[:])
		conn.SetDeadline(time.Now().Add(timeout))
		_, err :=conn.Write(payload)
		if err != nil {
    		log.Println(err)
			//fmt.Println("port "+port+" coming mark 8")
			resultChan <- dialResult{port: port, status: err.Error()}
			return
		}

		buf := bufPool.Get().([]byte)
		defer bufPool.Put(buf)

		_, err = conn.Read(buf)
		if err!=nil{
			log.Println(err)
			//fmt.Println("port "+port+" coming mark 9")
			resultChan <- dialResult{port: port, status: err.Error()}
			return
		}

		//need to implement logic if server was able to send something predictable
		//fmt.Println("Recieved foll msg from server - from port",port, "\n" ,buf[:n]) //change _ to n on line 144 for output
		//fmt.Println("port "+port+" coming mark 3")
		resultChan <- dialResult{port: port, status: "success for 53"}
		return

	case "123":
		payload := make([]byte, 48)
		payload[0] = 0x23 // LI=0 (2 bits 00), VN=4 (3 bits 100), Mode=3(3 bits 011) (Client) 00100011=dx35=0x23
		//rest of the packet would all be zeroes. Will have to change, if some NGF DPIs are hardened enough
		payload[2] = 0x6 //the poll interval - 6-10 seconds, according to AI
		payload[3] = 0xEC //=-20; payload[3] is unsigned 8-bit container. 0xec is 236, signed. 
							//The internal conversion from unsiged to signed is 236-256 = -20

		//payload[1] is stratum, which is suppoesed to be 0s ;payload[4:8] Root delay = 0.
		//payload[8:12] Root dispersion = 0 ; payload[12:16] refID = 0 on first req
		//payload[16:24], payload[24:32], payload[32,40] = ref timestamp, origin timestamp, recieve timestamp = 0
		//payload[40:49] is the transit timestamp, which should be ntp.Now, but go doesnt have that
		//for the cals, NTP epoch is Jan 1, 1900, Unix epoch is Jan 1, 1970 — difference is 70 years in seconds
		const ntpEpochOffset = 2208988800
		now := uint64(time.Now().Unix()) + ntpEpochOffset

		// seconds in bytes 40-43, fraction in bytes 44-47
		binary.BigEndian.PutUint32(payload[40:], uint32(now))
		binary.BigEndian.PutUint32(payload[44:], 0) // zeroes are prolly fine for fraction part
		//fmt.Println("NTP - ", payload[:])

		conn.SetDeadline(time.Now().Add(timeout))
		_, err := conn.Write(payload)
		if err != nil {
    		log.Println(err)
			//fmt.Println("port "+port+" coming mark 8")
			resultChan <- dialResult{port: port, status: err.Error()}
			return
		}

		buf := bufPool.Get().([]byte)
		defer bufPool.Put(buf)

		_, err = conn.Read(buf)
		if err!=nil{
			log.Println(err)
			//fmt.Println("port "+port+" coming mark 2")
			resultChan <- dialResult{port: port, status: err.Error()}
			return
		}

		//need to implement logic if server was able to send something predictable
		//fmt.Println("Recieved foll msg from server - from port",port, "\n" ,buf[:n]) change _ to n on line 191 for output
		//fmt.Println("port "+port+" coming mark 3")
		resultChan <- dialResult{port: port, status: "success for 123"}
		return

	default:
		//fmt.Println("debug for port ------", port)
		fmt.Fprintf(conn, "beacon from port : "+ port)
	
		// Borrow a buffer from the pool
		buf := bufPool.Get().([]byte)
		// Return to the pool when the function exits
		defer bufPool.Put(buf)

		n, err := conn.Read(buf)
		if err!=nil{
			log.Println(err)
			//fmt.Println("port "+port+" coming mark 2")
			resultChan <- dialResult{port: port, status: err.Error()}
			return
		}
		fmt.Println("Recieved foll msg from server - from port",port, "\n" ,string(buf[:n]))
		//fmt.Println("port "+port+" coming mark 3")
		resultChan <- dialResult{port: port, status: "success"}
		return
	}
	
}

func main(){
	//user input collection
	target  := flag.String("target", "", "C2 server IP address (required)")
    timeout = *flag.Duration("timeout", 3*time.Second, "probe timeout per port")
    ports   := flag.String("ports", "80,8080,443,53,123", "comma separated ports to probex")
    stealth := flag.Int("stealth", 0, "Introduce random jitter between each probes. goes 0-4. Higher the number, slowe the probes")
    
    flag.Parse()

    if *target == "" {
        fmt.Println("Error: -target is required")
        flag.Usage()
        return
    }
    c2_server_ip = *target
    sl:=*stealth
    port_list := strings.Split(*ports, ",")
	for i, p := range port_list {
    	port_list[i] = strings.TrimSpace(p)
	}

	//port_list := []string{"80", "8080", "443", "53", "123", "9001", "8443"}
	//supported ports from the server-side
	
	report := make(map[string]string)

	resultChan := make(chan dialResult, len(port_list))
	var wg sync.WaitGroup

	for _, port := range port_list{
		wg.Add(1)
		if sl >0{
			calculateAndJitter(sl)
		}
		go invokeParallelDialups(port, &wg, resultChan)
	}

	go func() {
		wg.Wait()
		close(resultChan)
	}()

	for i := 0; i < len(port_list); i++ {
		res := <-resultChan
		report[res.port] = res.status // Only main routine writes to map (Safe!)
	}

	fmt.Printf("---Final Report---\n")
	for key, val := range report{
		fmt.Println(key,"\t:\t", val)
	}
}

func calculateAndJitter(sl int){

	var baseDelay time.Duration
	switch sl{
	case 1:
		baseDelay = 2 * time.Second
	case 2:
		baseDelay = 20 * time.Second
	case 3:
		baseDelay = 10 * time.Minute
	case 4:
		fallthrough //anything greater than 4 gets a base delay of 2 hours
	default:
		baseDelay = 2 * time.Hour
	}

	//use a variance of +/-20 %
	minMultiplier := 0.8
	maxMultiplier := 1.2

	//calculate a random multiplier within that range
	randomMultiplier := minMultiplier + rand.Float64()*(maxMultiplier-minMultiplier)
	actualSleep := time.Duration(float64(baseDelay) * randomMultiplier)
	fmt.Println("Sleeping for ", actualSleep)
	time.Sleep(actualSleep)
	return
}
